#!/usr/bin/env bash
# ==============================================================================
# OmniVPN: Step 04 - Deploy IPsec / IKEv2 VPN Server
# ==============================================================================

set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=scripts/common.sh
source "${SCRIPT_DIR}/common.sh"

log_info "Step 04: Deploying IPsec / IKEv2 VPN Server on ${VPS_IP}..."

# 1. Create remote deployment directory
log_info "Preparing /opt/ipsec-vpn on remote host..."
run_ssh "mkdir -p /opt/ipsec-vpn"

# 2. Copy docker-compose.yml, vpn.env, and webui codebase
log_info "Synchronizing VPN & WebUI configuration files..."
run_scp "${PROJECT_ROOT}/docker/ipsec/docker-compose.yml" "/opt/ipsec-vpn/docker-compose.yml"
run_scp "${PROJECT_ROOT}/config/vpn.env" "/opt/ipsec-vpn/vpn.env"

# 2.5 Init WireGuard and Shadowsocks (Xray) directories
run_ssh 'bash -s' <<'INIT_EOF'
mkdir -p /opt/ipsec-vpn/wireguard /opt/ipsec-vpn/shadowsocks

# Initialize WG conf if not exists
if [ ! -f /opt/ipsec-vpn/wireguard/wg0.conf ]; then
  echo "[Interface]" > /opt/ipsec-vpn/wireguard/wg0.conf
  # Keys will be generated by the linuxserver/wireguard image or webui
fi

# Initialize Xray conf if not exists
if [ ! -f /opt/ipsec-vpn/shadowsocks/config.json ]; then
  cat > /opt/ipsec-vpn/shadowsocks/config.json <<'JSON'
{
  "inbounds": [{
    "port": 8388,
    "protocol": "shadowsocks",
    "settings": {
      "method": "aes-128-gcm",
      "password": "admin_placeholder",
      "network": "tcp,udp",
      "clients": []
    }
  }],
  "outbounds": [{
    "protocol": "freedom"
  }]
}
JSON
fi
INIT_EOF

# 3. Deploy containers via Docker Compose
log_info "Building & Starting IPsec VPN and WebUI containers..."
run_ssh 'bash -s' <<'REMOTE_EOF'
set -euo pipefail
cd /opt/ipsec-vpn
docker compose pull ipsec-vpn vpn-webui || true
docker compose up -d --remove-orphans

echo "[REMOTE] Waiting for services initialization (10s)..."
sleep 10

docker compose ps
docker logs vpn-webui --tail 20 || true
REMOTE_EOF

log_success "IPsec / IKEv2 VPN Server & WebUI are successfully deployed and running!"

